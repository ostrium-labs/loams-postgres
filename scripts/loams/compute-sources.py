#!/usr/bin/env python3
"""The compute image's source artifact (LP-0012, NF1 Task 12).

    compute-sources.py [--pg-version v<N>] [compute/compute-node.Dockerfile] > sources.Dockerfile

Prints the compute Dockerfile with two stages appended:

    loams-sources       collects, from every `<name>-src` stage, the tarballs and
                        patches the build downloaded or applied (`/ext-src/*.tar.gz`,
                        `*.patch`), each renamed `<stage>--<file>`, and Postgres'
                        own tree (vendor/postgres-${PG_VERSION}) as a tarball,
                        with a SHA256SUMS file over all of them;
    loams-sources-out   those files alone (FROM scratch), for
                        `docker buildx build --target loams-sources-out --output type=tar`.

loams-sign.yml attaches that tar to the compute image's index with
`oras attach --artifact-type application/vnd.loams.sources.v1`, so every GPL
component (PostGIS, pgRouting, postgresql-unit, SFCGAL) ships with its source.
The stages are generated, not kept in the Dockerfile, so a new `-src` stage is
covered without an edit. With --pg-version v<N> for a major built with its own
`extensions-v<N>` layer (NF2 Task 8), only the `-src` stages of the extensions
in that layer are collected. Every `git clone` (plv8, pg_duckdb, pgbouncer; none of
them GPL) is also listed in GIT-SOURCES with its URL and tag; plv8's stage packs
its clone as plv8.tar.gz, which is collected like the tarballs.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC_STAGE = re.compile(r"^FROM \S+ AS ([a-z0-9_-]+-src)$", re.M)
GIT_CLONE = re.compile(r"git clone [^\n]*?(?:--branch (\S+) )?(https://\S+?)(?:\.git)?\s")


def src_stages(dockerfile_text, pg_version=None):
    names = SRC_STAGE.findall(dockerfile_text)
    if pg_version:
        layer = re.search(rf"(?ms)^FROM \S+ AS extensions-{re.escape(pg_version)}$(.*?)(?=^FROM )", dockerfile_text)
        if layer:
            built = set(re.findall(r"(?m)^COPY\s+(?:--\S+\s+)*--from=(\S+)", layer.group(1)))
            names = [n for n in names if n[: -len("-src")] + "-build" in built]
    return names


def git_sources(dockerfile_text):
    out = set()
    for branch, url in GIT_CLONE.findall(dockerfile_text):
        if not branch:
            branch = "(default branch)"
        elif branch.startswith("${"):
            # A tag the Dockerfile sets in that stage (per major for plv8).
            branch = f"(the {branch.strip('${}')} the Dockerfile sets)"
        out.add(f"{url} {branch}")
    return sorted(out)


def stages(dockerfile_text, pg_version=None):
    names = src_stages(dockerfile_text, pg_version)
    if not names:
        raise SystemExit("compute-sources: no -src stage found")
    mounts = " \\\n".join(
        f"    --mount=type=bind,from={n},source=/ext-src,target=/in/{n}" for n in names
    )
    git = "\\n".join(git_sources(dockerfile_text))
    return f"""

#########################################################################################
#
# Generated by scripts/loams/compute-sources.py (LP-0012): the source artifact.
#
#########################################################################################
FROM build-deps AS loams-sources
ARG PG_VERSION
USER root
COPY vendor/postgres-${{PG_VERSION}} /tmp/postgres-${{PG_VERSION}}
RUN \\
{mounts} \\
    set -e && mkdir -p /sources && \\
    for dir in /in/*; do \\
        stage=$(basename "$dir"); \\
        find "$dir" -maxdepth 1 -type f \\( -name '*.tar.gz' -o -name '*.tgz' -o -name '*.patch' \\) \\
            -exec sh -c 'cp "$1" "/sources/$2--$(basename "$1")"' _ {{}} "$stage" \\; ; \\
    done && \\
    tar -C /tmp --sort=name --mtime=@0 --owner=0 --group=0 -czf "/sources/postgres-${{PG_VERSION}}.tar.gz" "postgres-${{PG_VERSION}}" && \\
    printf '%b\\n' "Sources fetched with git clone (URL and tag; none is GPL):\\n{git}" > /sources/GIT-SOURCES && \\
    cd /sources && sha256sum -- * > /tmp/SHA256SUMS && mv /tmp/SHA256SUMS /sources/SHA256SUMS

FROM scratch AS loams-sources-out
COPY --from=loams-sources /sources/ /
"""


def main(argv):
    args = argv[1:]
    pg_version = None
    if args[:1] == ["--pg-version"]:
        if len(args) < 2 or not re.fullmatch(r"v[0-9]+", args[1]):
            print("compute-sources: --pg-version needs v<N>", file=sys.stderr)
            return 2
        pg_version, args = args[1], args[2:]
    path = Path(args[0]) if args else ROOT / "compute" / "compute-node.Dockerfile"
    text = path.read_text()
    sys.stdout.write(text + stages(text, pg_version))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
